// Derives site pages from documents that live outside the docs tree.
//
// The quickstart is the release-candidate acceptance path and belongs to the
// specification directory, where it is reviewed and executed. Copying it here
// would create a second copy that reads as authoritative and goes stale
// silently, which is the failure the generated-artifact drift job in CI exists
// to catch. So it is generated at build time and never committed: there is one
// source of truth and no copy to fall behind it.
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, '../..');

/** @type {{source: string, target: string, frontmatter: Record<string,string>, note: string}[]} */
const pages = [
	{
		source: 'specs/001-cloud-native-nsm/quickstart.md',
		target: 'docs/src/content/docs/quickstart.md',
		frontmatter: {
			title: 'Quickstart',
			description:
				'The release-candidate acceptance path: install Trawl, then validate every user story against a real cluster.',
		},
		note: 'This page is generated from `specs/001-cloud-native-nsm/quickstart.md`. Edit that file — changes made here are overwritten by the next build.',
	},
];

const quote = (value) => `"${value.replaceAll('"', '\\"')}"`;

for (const page of pages) {
	const raw = await readFile(resolve(repo, page.source), 'utf8');

	// Starlight renders the frontmatter title as the page h1, so the document's
	// own top-level heading has to go or every page ships two.
	const body = raw.replace(/^#\s+.*\r?\n+/, '');

	const frontmatter = Object.entries(page.frontmatter)
		.map(([key, value]) => `${key}: ${quote(value)}`)
		.join('\n');

	const out = resolve(repo, page.target);
	await mkdir(dirname(out), { recursive: true });
	await writeFile(
		out,
		`---\n${frontmatter}\n# Generated by docs/scripts/sync-content.mjs from ${page.source}. Do not edit.\neditUrl: false\n---\n\n:::note\n${page.note}\n:::\n\n${body}`,
	);
	console.log(`synced ${page.target} from ${page.source}`);
}
